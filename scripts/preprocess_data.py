#!/usr/bin/env python3
"""
CSV → JSON pipeline: Generate web-optimized artefacts from consolidated cyclone data.

Run from the project root:
    python3 scripts/preprocess_data.py

Input:
    data/processed/tracks_south_atlantic_consolidated.csv
    (generated by: python scripts/data/run_pipeline.py)

Output:
    site/public/data/summary.json          — one entry per track (metadata + simplified line coords)
    site/public/data/details/{year}.json   — full timestep data per year, loaded on demand by the web app

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Data sources
------------
The consolidated CSV contains data from:
    - Cyclone tracks: Gramcianinov et al. (2019), Mendeley Data, DOI: 10.17632/kwcvfr52hp.4
    - LEC diagnostics: Zenodo, DOI: 10.5281/zenodo.18133432
    - Genesis regions: Gramcianinov et al. (2019), Climate Dynamics
    - Lifecycle phases: Cyclophaser (de Souza et al., JOSS 2025)

Genesis region classification
-----------------------------
The source data includes pre-computed region labels (ARG, LA-PLATA, SE-BR).
For display, these are mapped to more descriptive names.

Lifecycle phase labels
----------------------
Phase labels (incipient, intensification, mature, decay, etc.) are pre-computed
in the source dataset using the Cyclophaser tool:

    de Souza, D. C., da Dias, P. L. S., Gramcianinov, C. B., & de Camargo, R. (2025).
    Cyclophaser: A Python package for detecting extratropical cyclone life cycles.
    Journal of Open Source Software, 10(108), 7363.
    https://doi.org/10.21105/joss.07363

Temporal resolution note
------------------------
    - Track positions (lon, lat, vor42): 1-hourly
    - LEC energetics (Kz, Ke, Ck, Ca, etc.): 3-hourly (NaN at intermediate hours)

This is expected behavior. The JSON output omits NaN energetics values; the web
app displays "LEC diagnostics not available at this timestep" for those hours.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
"""

