def compute_thresholds(values: np.ndarray) -> dict:
    """Quantile thresholds for one display variable's track-level peaks.

    p10 and max bound the colour ramp; the rest draw the guide lines and the
    shortcut chips in the intensity filter. Computed per variable, never reused
    across variables - a threshold in x10^-5 s^-1 means nothing in m s^-1.
    """
    v = np.asarray(values, dtype="float64")
    v = v[np.isfinite(v)]
    return {
        "p10": float(np.quantile(v, 0.10)),
        "p25": float(np.quantile(v, 0.25)),
        "p50": float(np.quantile(v, 0.50)),
        "p75": float(np.quantile(v, 0.75)),
        "p90": float(np.quantile(v, 0.90)),
        "p95": float(np.quantile(v, 0.95)),
        "max": float(v.max()),
    }


def load_wind_intensity(path: Path) -> dict:
    """
    Per-cyclone wind intensity, read from the consolidated base.

    data/processed/cyclones.parquet is produced by scripts/data/merge_wind.py
    and already holds max_wind10 / max_wind100 computed the same way for every
    level. Reading it here rather than recomputing keeps a single definition of
    track intensity in the pipeline.

    Returns {track_id: {"max_wind10": float|None, "max_wind100": float|None}},
    or {} when the base has not been built - the site then simply offers the
    vorticity display variable alone.
    """
    if not path.exists():
        print(f"  ! Consolidated base not found: {path}")
        print("    Wind display variables will be unavailable.")
        print("    Build it with: python scripts/data/merge_wind.py")
        return {}

    cols = ["track_id", "max_wind10", "max_wind100"]
    df = pd.read_parquet(path, columns=cols)
    out = {}
    for r in df.itertuples(index=False):
        out[int(r.track_id)] = {
            "max_wind10":  None if pd.isna(r.max_wind10) else float(r.max_wind10),
            "max_wind100": None if pd.isna(r.max_wind100) else float(r.max_wind100),
        }
    n10 = sum(1 for v in out.values() if v["max_wind10"] is not None)
    n100 = sum(1 for v in out.values() if v["max_wind100"] is not None)
    print(f"  Wind intensity: {len(out):,} cyclones "
          f"({n10:,} with 10 m, {n100:,} with 100 m)")
    return out


def load_cps_classification(path: Path) -> dict:
    """
    Load the per-cyclone CPS classification, keyed by track_id.

    Returns {} when the file is absent — CPS is optional and the site degrades
    gracefully (the type filter simply reports no data).

    Each entry carries:
        cls        phase_class code (EC, SC, ST, ...)
        label      human-readable expansion
        group      coarse grouping for the filter UI
        seq        state_sequence, e.g. "EC->SC" (None when absent)
        warm_secl  True when the identification guards rejected at least one
                   run as a Shapiro–Keyser warm seclusion. This is NOT a
                   phase_class: it is a property of the rejected runs, exposed
                   separately because it is scientifically interesting on its own.
    """
    if not path.exists():
        print(f"  ⚠ CPS classification not found: {path}")
        print("    Cyclone type filter will be empty.")
        return {}

    df = pd.read_csv(path)
    print(f"  CPS classification: {len(df):,} cyclones")

    out = {}
    for _, r in df.iterrows():
        code = str(r.get("phase_class", "no_cps_data"))
        n_ws = r.get("n_warm_seclusions", 0)
        try:
            n_ws = float(n_ws)
        except (TypeError, ValueError):
            n_ws = 0.0
        seq = r.get("state_sequence")
        if isinstance(seq, float) and math.isnan(seq):
            seq = None
        group = CPS_CLASS_GROUPS.get(code, "Undetermined")
        out[int(r["track_id"])] = {
            "cls":       code,
            "label":     CPS_CLASS_LABELS.get(code, code),
            "group":     group,
            # Read from the export when present; the map is the fallback so an
            # older CSV still yields a correct flag.
            "identified": bool(r["is_identified"]) if "is_identified" in r
                          and pd.notna(r.get("is_identified"))
                          else group in CPS_IDENTIFIED_GROUPS,
            "seq":       str(seq) if seq is not None else None,
            "warm_secl": bool(n_ws and n_ws > 0),
        }
    return out


def build_intensity_pdf(values: np.ndarray, thresholds: dict) -> dict:
    """
    Histogram of one display variable's track-level peaks, for the filter's PDF.

    Returns bin edges, the normalised density, and raw counts. The density is a
    proper probability density (integrates to 1 over the value axis), so the
    curve is comparable regardless of bin count.
    """
    counts, edges = np.histogram(values, bins=INTENSITY_PDF_BINS)
    widths = np.diff(edges)
    total = counts.sum()
    density = (counts / total / widths) if total > 0 else np.zeros_like(counts, dtype=float)

    return {
        "bin_edges": [round(float(e), 4) for e in edges],
        "counts":    [int(c) for c in counts],
        "density":   [round(float(d), 6) for d in density],
        "min":       round(float(values.min()), 4),
        "max":       round(float(values.max()), 4),
        "n":         int(values.size),
        # Repeated here so the chart can draw quantile guide lines without
        # cross-referencing another object.
        "quantiles": {k: round(float(v), 4) for k, v in thresholds.items()},
    }


def downsample_coords(lons, lats, max_pts: int = MAX_COORDS_PER_TRACK):
    n = len(lons)
    if n <= max_pts:
        indices = list(range(n))
    else:
        step    = n / max_pts
        indices = [int(i * step) for i in range(max_pts)]
        if indices[-1] != n - 1:
            indices[-1] = n - 1
    return [
        [round(float(lons[i]), COORD_DECIMALS), round(float(lats[i]), COORD_DECIMALS)]
        for i in indices
    ]


